def small_class(name, body="int x = 1;"):
    return f"package game;\n\nclass {name} {{\n    void f() {{\n        {body}\n    }}\n}}\n"


def _commit(repo, message, files=None, delete=(), move=None):
    root = Path(repo.working_tree_dir)
    for old, new in (move or {}).items():
        (root / new).parent.mkdir(parents=True, exist_ok=True)
        repo.git.mv(old, new)
    for rel, text in (files or {}).items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8"))
    for rel in delete:
        repo.git.rm(rel)
    repo.git.add("-A")
    repo.git.commit("-m", message)
    return repo.head.commit.hexsha


def build_history(path):
    repo = git.Repo.init(path)
    with repo.config_writer() as cw:
        cw.set_value("user", "name", "Test Dev")
        cw.set_value("user", "email", "Dev@Example.COM")
        cw.set_value("commit", "gpgsign", "false")
        cw.set_value("core", "autocrlf", "false")
    shas = {}
    player, world, hud, enemy = PLAYER, WORLD, HUD, ENEMY

    shas["root"] = _commit(repo, "root", {"src/game/Player.java": player, "src/game/World.java": world,
                                          "src/game/Hud.java": hud, "README.md": "toy\n"})
    main = repo.active_branch.name

    player = player.replace("x += dx;\n", 'x += dx;\n        LOG.info("moving player to " + x);\n')
    shas["add"] = _commit(repo, "add log", {"src/game/Player.java": player})

    player = player.replace('        LOG.warn("damage taken: " + amount);\n', "")
    shas["remove"] = _commit(repo, "remove log", {"src/game/Player.java": player})

    player = player.replace('LOG.info("tick " + tpf);', 'LOG.warn("tick " + tpf);')
    world = world.replace("Level.INFO", "Level.FINE").replace(
        'logger.warning("Failed to load map " + name);', 'logger.log(Level.WARNING, "Failed to load map " + name);')
    shas["level"] = _commit(repo, "change levels", {"src/game/Player.java": player, "src/game/World.java": world})

    player = player.replace('        LOG.debug("healing player by " + amount);\n', "").replace(
        "hp++;\n", 'hp++;\n        LOG.debug("healing player by " + amount);\n')
    shas["relocate"] = _commit(repo, "relocate log", {"src/game/Player.java": player})

    shas["new_file"] = _commit(repo, "new files", {
        "src/game/Enemy.java": enemy, "src/game/FooTest.java": FOO_TEST, "src/game/Stub.java": STUB,
        "src/game/Codec.java": CODEC, "src/game/generated/Proto.java": PROTO})

    enemy = enemy.replace("    public void attack", '    public void spawn() {\n        LOG.info("spawned enemy");\n    }\n\n    public void attack')
    shas["new_method"] = _commit(repo, "new method", {"src/game/Enemy.java": enemy})

    shas["test_change"] = _commit(repo, "test change", {
        "src/game/FooTest.java": FOO_TEST.replace("check();", 'check();\n        LOG.info("checked");')})

    player = player.replace("    public void idle() {\n        x = x + 0;\n    }",
                            "    public void idle()\n    {\n        // nothing to do here\n        x   =   x + 0;\n    }")
    shas["whitespace"] = _commit(repo, "whitespace only", {"src/game/Player.java": player})

    hud = hud.replace('GLog.w("You are hungry");', 'GLog.i("You are hungry");\n        GLog.p("welcome back");')
    shas["glog"] = _commit(repo, "game messages", {"src/game/Hud.java": hud})

    repo.git.checkout("-b", "side")
    enemy = enemy.replace("p.damage(3);", "p.damage(5);")
    shas["side"] = _commit(repo, "side change", {"src/game/Enemy.java": enemy})
    repo.git.checkout(main)
    repo.git.merge("side", "--no-ff", "-m", "merge side")
    shas["merge"] = repo.head.commit.hexsha

    enemy = enemy.replace("p.damage(5);", 'p.damage(5);\n        LOG.debug("attacking " + p);')
    shas["rename_file"] = _commit(repo, "move enemy", {"src/game/mobs/Enemy.java": enemy},
                                  move={"src/game/Enemy.java": "src/game/mobs/Enemy.java"})

    player = player.replace("public void regen(int amount)", "public void regenerate(int amount)").replace(
        "public void damage(int amount) {\n        hp -= amount;",
        "public void damage(int amount, String source) {\n        hp -= amount;\n        last = source;")
    shas["rename_method"] = _commit(repo, "rename methods", {"src/game/Player.java": player})

    player = player.replace("x   =   x + 0;", 'x   =   x + 0;\n        LOG.trace("idle");')
    bulk_files = {"src/game/Player.java": player,
                  "src/game/World.java": world.replace("void load", "void load2"),
                  "src/game/Hud.java": hud.replace("void show", "void display"),
                  "src/game/mobs/Enemy.java": enemy.replace("p.damage(5);", "p.damage(6);")}
    for k in range(3):
        bulk_files[f"src/game/extra/Extra{k}.java"] = small_class(f"Extra{k}")
    shas["bulk"] = _commit(repo, "bulk change", bulk_files)

    enemy = enemy.replace('    public void spawn() {\n        LOG.info("spawned enemy");\n    }\n\n', "")
    shas["delete"] = _commit(repo, "delete things", {"src/game/mobs/Enemy.java": enemy.replace("p.damage(5);", "p.damage(6);")},
                             delete=["src/game/Hud.java"])
    return repo, shas


def read_jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f]


