def _commit(repo, files, message, who, date):
    for rel, text in files.items():
        p = os.path.join(repo.working_tree_dir, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    repo.index.add(list(files))
    actor = git.Actor(who, f"{who.lower()}@example.com")
    return repo.index.commit(message, author=actor, committer=actor, author_date=date, commit_date=date)


