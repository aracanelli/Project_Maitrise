def test_statement_matcher_is_global_greedy():
    f = lambda text: {"call_text": text, "logging_style": "formal"}
    pre = [f('log.info("loading map")'), f('log.info("loading map tiles")')]
    post = [f('log.info("loading map tiles")'), f('log.warn("loading maps")')]
    pairs, un_pre, un_post = match_statements(pre, post)
    # upstream's nested loop maps pre[0]->post[0], then lets pre[1] take post[0] and never
    # revisits pre[0], leaving pre[0] and post[1] unmatched; the global greedy pairs both
    assert [p[:2] for p in pairs] == [(0, 1), (1, 0)] and un_pre == [] and un_post == []
    assert pairs[1][2] == 1.0
    one = [f('log.info("player joined")'), f('log.info("player joined game")')]
    pairs, un_pre, _ = match_statements(one, [f('log.info("player joined game!")')])
    assert [p[:2] for p in pairs] == [(1, 0)] and un_pre == [0]

    styles = [{"call_text": 'System.out.println("x")', "logging_style": "informal_print"}]
    formal = [{"call_text": 'System.out.println("x")', "logging_style": "formal"}]
    assert match_statements(styles, formal) == ([], [0], [0])
    a = [{"call_text": "ab", "logging_style": "formal"}]
    b = [{"call_text": "ac", "logging_style": "formal"}]   # ratio exactly 0.5: not above the threshold
    assert match_statements(a, b)[0] == []


