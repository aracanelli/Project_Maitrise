"""
Commit order, per-commit Java file diffs and blob access for history mining.

Adapted from the replication package of Zeng et al. (2019):
  logdetector/utils/githelper.py (get_project_repository, get_diff_between_commits,
  get_diff_of_initial_commit, EMPTY_TREE_SHA) and logdetector/detector.py
  (detect_project: one diff per commit against its parent, empty tree for the root).

Differences from upstream:
- commits are walked in `git rev-list --topo-order --reverse <pinned head>` order
  instead of `git log` order
- nothing is pulled, reset or checked out; blobs are read from the object database
- merge commits are listed but not diffed; a non-merge commit is diffed against its
  first parent with rename detection (GitPython default -M); upstream diffed every parent
- only Java files are kept, and test and generated files are recognised here
"""

import re
import subprocess

import git

from src.detection.scan import _looks_like_test

EMPTY_TREE_SHA = "4b825dc642cb6eb9a060e54bf8d69288fbee4904"

# first top-level type declaration line: everything before it (and the line itself) is the file header
_TYPE_DECL = re.compile(
    rb"^[ \t]*(?:@[\w.]+(?:\([^)\n]*\))?[ \t]+)*"
    rb"(?:(?:public|protected|private|abstract|final|static|sealed|non-sealed|strictfp)[ \t]+)*"
    rb"(?:class|interface|enum|record|@interface)[ \t]+\w",
    re.M,
)


def open_repo(repo_dir):
    repo = git.Repo(str(repo_dir))
    assert not repo.bare
    return repo


def run_git(repo_dir, args):
    res = subprocess.run(["git", "-C", str(repo_dir)] + args, capture_output=True)
    if res.returncode != 0:
        raise RuntimeError(f"git {' '.join(args[:3])} failed: {res.stderr.decode('utf-8', 'replace')}")
    return res.stdout.decode("utf-8", "replace")


def list_commits(repo_dir, head):
    """Commits reachable from head in `rev-list --topo-order --reverse` order.

    Returns (sha, parent_shas, committer_date_iso, author_email) tuples; parents come
    before children, so the position in this list is the topo_index.
    """
    out = run_git(repo_dir, ["rev-list", "--topo-order", "--reverse",
                             "--format=%x01%H%x1f%P%x1f%cI%x1f%ae", head])
    commits = []
    for line in out.splitlines():
        if not line.startswith("\x01"):
            continue  # the "commit <sha>" header lines of rev-list --format
        sha, parents, date, email = line[1:].split("\x1f")
        commits.append((sha, parents.split(), date, email))
    return commits


def is_java(path):
    return bool(path) and path.lower().endswith(".java")


def is_test_path(path):
    return _looks_like_test(path)


def is_generated_path(path, segments):
    if not path:
        return False
    wanted = {s.lower() for s in segments}
    return any(part.lower() in wanted for part in path.replace("\\", "/").split("/")[:-1])


def has_generated_header(data, markers, limit=2000):
    """True if a generated-code marker appears in the file header.

    The header is the part of the first `limit` bytes up to (and including) the first
    top-level type declaration line. Markers further down are ignored: Eclipse puts
    "// TODO Auto-generated method stub" inside method bodies of hand-written code, and
    NetBeans form classes mention "regenerated by the Form Editor" in a method javadoc.
    """
    head = data[:limit]
    m = _TYPE_DECL.search(head)
    if m:
        end = head.find(b"\n", m.end())
        if end >= 0:
            head = head[:end]
    text = head.decode("utf-8", "replace").lower()
    return any(marker.lower() in text for marker in markers)


def java_changes(repo, commit_id, parent_id):
    """Java file changes of a commit against its first parent (empty tree for a root).

    Each change is a dict with change_type (A|D|M|R), old_path, new_path, old_blob,
    new_blob. Type changes (T) are reported as M.
    """
    commit = repo.commit(commit_id)
    if parent_id:
        diffs = repo.commit(parent_id).diff(commit)
    else:
        diffs = repo.tree(EMPTY_TREE_SHA).diff(commit)

    changes = []
    for d in diffs:
        ct = d.change_type
        if ct == "T":
            ct = "M"
        if ct not in ("A", "D", "M", "R"):
            continue
        old_path = d.a_path if ct != "A" else None
        new_path = d.b_path if ct != "D" else None
        if not (is_java(old_path) or is_java(new_path)):
            continue
        changes.append({
            "change_type": ct,
            "old_path": old_path,
            "new_path": new_path,
            "old_blob": d.a_blob.hexsha if (d.a_blob is not None and ct != "A") else None,
            "new_blob": d.b_blob.hexsha if (d.b_blob is not None and ct != "D") else None,
        })
    return changes


def read_blob(repo, blob_sha):
    return repo.odb.stream(bytes.fromhex(blob_sha)).read()
