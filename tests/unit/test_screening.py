def test_generated_rule_is_the_mining_rule():
    markers = load_config("extraction")["generated_header_markers"]
    after_imports = "package a;\nimport b.C;\n/** Generated by Protoc, do not edit. */\npublic class B {}\n"
    member = "package a;\npublic class B {\n    @Generated(\"x\")\n    void f() {}\n}\n"
    class_level = "package a;\n@Generated(\"x\")\npublic class B {}\n"
    cases = [(GENERATED, "header"), (STUB, None), (after_imports, "header"), (member, None), (class_level, "header")]
    for src, want in cases:
        assert generated_reason("a/B.java", src) == want
        assert has_generated_header(src.encode("utf-8"), markers) == (want == "header")
    assert generated_reason("a/generated/B.java") == "path"
    assert generated_reason("a/B.java", GENERATED.encode("utf-8")) == "header"


ARROW_SWITCH = '''class A {
 void f(int k) {
  switch (k) {
   case 1 -> {
    log.info("arrow");
    System.out.println("p");
    if (k > 0) {
     log.warn("nested");
    }
    System.out.println("after if");
   }
   case 2 -> log.debug("bare");
  }
  switch (k) {
   default -> log.error("default");
  }
 }
}
'''


def test_arrow_switch_rules_are_detected():
    src = 'class A { void f(int k) { switch (k) { case 1 -> { log.info("arrow"); } default -> { } } log.info("after"); } }'
    res = screen_source("A.java", src)
    assert [(l["text"], l["rule"], l["context"]) for l in res["logs"]] == [
        ('log.info("arrow")', "switch_rule", "branch"), ('log.info("after")', "", "method_top")]
    assert res["text_only"] == [] and res["rejected"] == []
    res = screen_source("A.java", ARROW_SWITCH)
    # direct statements of a rule block and a braceless case rule are statements
    assert [(l["line"], l["style"], l["rule"], l["lambda_body"]) for l in res["logs"]] == [
        (5, "formal", "switch_rule", False), (6, "informal_print", "switch_rule", False),
        (12, "formal", "switch_rule", False)]
    # still missed: nested in an if of the block (8), swallowed after it (10), default as the only rule (15)
    assert [(t["line"], t["style"], t["cause"]) for t in res["text_only"]] == [
        (8, "formal", "switch_rule"), (10, "informal_print", "switch_rule"), (15, "formal", "switch_rule")]
    d = difference_row({"name": "A", "files": [res], "skipped": []}, {})
    assert d["formal_switch_rule"] == 2 and d["informal_switch_rule"] == 1 and d["formal_lambda_body"] == 0
    assert d["text_only_formal"] == 2 and d["text_only_informal"] == 1 and d["text_only_switch_rule"] == 3


