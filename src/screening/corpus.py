"""
Corpus-level helpers: which Java files of a snapshot are analysed, and the reference
counts collected by hand in the Game List spreadsheet (proposal Table 3.2).

File filters (configs/extraction.yaml):
- test files: src.detection.scan._looks_like_test (/test/, /tests/, Test*, *Test(s))
- generated files: a path segment from generated_path_segments, or a marker from
  generated_header_markers (e.g. "@Generated", "generated by") in the file header.
  History mining uses the same two checks (src.mining.git_walker.is_generated_path /
  has_generated_header; header = first 2000 bytes up to the first type-declaration line),
  so RQ1 and mining exclude the same files. Markers further down are ignored because IDE
  stubs such as "// TODO Auto-generated method stub" appear inside hand-written method bodies.
"""

import re
import zipfile

from lxml import etree

from src.common.config import load_config
from src.detection.scan import _looks_like_test
from src.mining.git_walker import is_generated_path, has_generated_header


def is_test_path(path):
    return _looks_like_test(path)


def generated_reason(path, source=None):
    """None if the file is hand-written, else 'path' or 'header'."""
    cfg = load_config("extraction")
    if is_generated_path(path, cfg["generated_path_segments"]):
        return "path"
    if source is None:
        return None
    if isinstance(source, str):
        source = source.encode("utf-8")
    if has_generated_header(source, cfg["generated_header_markers"]):
        return "header"
    return None


def is_generated(path, source=None):
    return generated_reason(path, source) is not None


_XL = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"


def _read_xlsx_rows(path):
    """First sheet of an .xlsx as a list of rows (strings). Used when openpyxl is missing."""
    with zipfile.ZipFile(path) as z:
        strings = []
        if "xl/sharedStrings.xml" in z.namelist():
            for si in etree.fromstring(z.read("xl/sharedStrings.xml")).iter(_XL + "si"):
                strings.append("".join(t.text or "" for t in si.iter(_XL + "t")))
        sheet = etree.fromstring(z.read("xl/worksheets/sheet1.xml"))
    rows = []
    for row in sheet.iter(_XL + "row"):
        cells = {}
        for c in row.iter(_XL + "c"):
            col = re.match(r'[A-Z]+', c.get("r")).group(0)
            v = c.find(_XL + "v")
            if v is not None:
                val = strings[int(v.text)] if c.get("t") == "s" else v.text
            else:
                val = "".join(t.text or "" for t in c.iter(_XL + "t"))
            cells[col] = val
        rows.append(cells)
    if not rows:
        return []
    cols = sorted({k for r in rows for k in r}, key=lambda k: (len(k), k))
    return [[r.get(k) for k in cols] for r in rows]


def read_game_list(path):
    """{repo_name: {"commits", "loc", "formal", "informal"}} from the Game List sheet.

    Names such as "jme3rpg (ANJRpg)" are reduced to the part before the parenthesis
    so they match configs/corpus.yaml.
    """
    try:
        import pandas as pd
        df = pd.read_excel(path)
        header = list(df.columns)
        body = df.values.tolist()
    except ImportError:
        rows = _read_xlsx_rows(path)
        header, body = rows[0], rows[1:]
    idx = {name: i for i, name in enumerate(header)}
    out = {}
    for row in body:
        repo = row[idx["Repo"]]
        if repo is None or str(repo).strip() in ("", "nan"):
            continue
        name = str(repo).split("(")[0].strip()
        out[name] = {
            "commits": _num(row[idx["Commits"]]),
            "loc": _num(row[idx["Java LOC"]]),
            "formal": _num(row[idx["Formal Log Stmts"]]),
            "informal": _num(row[idx["Informal (sysout/trace)"]]),
        }
    return out


def _num(v):
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return None
