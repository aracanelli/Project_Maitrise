def check_row_invariants(rows):
    for r in rows:
        pre_sides = [r["removed_formal_pre"], r["relocated_pre"], [m[0] for m in r["matched_formal"]]]
        post_sides = [r["added_formal_post"], r["relocated_post"], [m[1] for m in r["matched_formal"]]]
        assert sorted(sum(pre_sides, [])) == list(range(r["n_pre_formal"]))
        assert sorted(sum(post_sides, [])) == list(range(r["n_post_formal"]))
        assert len(r["pre_levels"]) == r["n_pre_formal"] and len(r["post_levels"]) == r["n_post_formal"]
        assert r["n_pre_logs_all"] >= r["n_pre_formal"]
        for pre_fi, post_fi in r["level_changed"]:
            assert r["pre_levels"][pre_fi] != r["post_levels"][post_fi]
            assert [pre_fi, post_fi] in [m[:2] for m in r["matched_formal"]]
        assert isinstance(r["block_changed"], bool) and r["class_path_pre"]
        if r["match_pass"] == 3:
            assert not r["block_changed"]   # pass 3 pairs identical blocks
        if not r["block_changed"]:
            # an identical block has the same statements, so nothing logging-related can change
            assert not (r["added_formal_post"] or r["removed_formal_pre"] or r["level_changed"]
                        or r["relocated_pre"] or r["relocated_post"] or r["other_log_change"])


def test_method_rows_invariants_and_event_consistency(mined):
    rows = mined["methods_changed"]
    assert rows
    check_row_invariants(rows)

    # every core event is listed in exactly one methods_changed row, and the other way round
    index = {}
    for r in rows:
        key = (r["commit_id"], r["pre_path"], r["post_path"], r["pre_ordinal"], r["post_ordinal"])
        assert key not in index
        index[key] = r
    listed = {"ADD_LOG": 0, "REMOVE_LOG": 0, "CHANGE_LEVEL": 0}
    for r in rows:
        if not r["is_bulk"]:
            listed["ADD_LOG"] += len(r["added_formal_post"])
            listed["REMOVE_LOG"] += len(r["removed_formal_pre"])
            listed["CHANGE_LEVEL"] += len(r["level_changed"])
    core = {"ADD_LOG": 0, "REMOVE_LOG": 0, "CHANGE_LEVEL": 0}
    for e in mined["events"]:
        if e["scope"] == "modified_method":
            r = index[(e["commit_id"], e["pre_path"], e["post_path"], e["pre_ordinal"], e["post_ordinal"])]
            if e["logging_style"] != "formal":
                assert r["other_log_change"]
        if e["validity_status"] != "core":
            continue
        core[e["event_label"]] += 1
        r = index[(e["commit_id"], e["pre_path"], e["post_path"], e["pre_ordinal"], e["post_ordinal"])]
        if e["event_label"] == "ADD_LOG":
            assert e["post_formal_index"] in r["added_formal_post"]
        elif e["event_label"] == "REMOVE_LOG":
            assert e["pre_formal_index"] in r["removed_formal_pre"]
        else:
            assert [e["pre_formal_index"], e["post_formal_index"]] in r["level_changed"]
    assert core == listed
    assert core == {"ADD_LOG": 2, "REMOVE_LOG": 1, "CHANGE_LEVEL": 2}
    assert mined["summary"]["core_events"] == core


